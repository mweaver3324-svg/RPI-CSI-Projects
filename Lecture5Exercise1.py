#Calls three functions of the same name to convert a given temperature in celcius to fahrenheit
def conver2fahren():
    celcius = 0
    fahrenheit = celcius * 1.8 + 32
    print("0 ->",fahrenheit)
conver2fahren()  

def conver2fahren():
    celcius = 32
    fahrenheit = celcius * 1.8 + 32
    print("32 ->", fahrenheit)
conver2fahren() 

def conver2fahren():
    celcius = 100
    fahrenheit = celcius * 1.8 + 32
    print("100 ->", fahrenheit)
conver2fahren()




    
